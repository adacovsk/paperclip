def sweep(api: Api, project: Path) -> None:
    roster = api.get(f"/companies/{api.company}/agents")
    agents = {a["name"]: a["id"] for a in roster}
    worker = next(a for a in roster if a["name"] == "Worker")

    owned = api.issues(status="in_review", assigneeAgentId=agents["Worker"])
    parents = [p for p in owned if not stage_of(p)]
    # A finished rebase's parent may be parked anywhere (a conflict hold blocks
    # it), so it joins the sweep by its child rather than by its own status.
    listed = {p["id"] for p in parents}
    for rebase in owned:
        if finished_rebase(rebase) and rebase.get("parentId") and rebase["parentId"] not in listed:
            listed.add(rebase["parentId"])
            parents.append(api.get(f"/issues/{rebase['parentId']}"))
    # So may a parent whose stage stopped on a conflict: it waits on a rebase
    # nothing else would dispatch.
    for stalled in api.issues(status="blocked"):
        if stage_of(stalled) in ("verify", "review") and stalled.get("parentId") and stalled["parentId"] not in listed:
            listed.add(stalled["parentId"])
            parents.append(api.get(f"/issues/{stalled['parentId']}"))

    def load(parent: dict):
        children = api.issues(parentId=parent["id"])
        if live_stage(ordered_stages(children)):
            return parent, children, None  # a stage is live: no git read needed
        full = api.get(f"/issues/{parent['id']}")
        return full, children, git_state(project, parent["identifier"])

    with concurrent.futures.ThreadPoolExecutor(8) as pool:
        loaded = list(pool.map(load, parents))
    pr_heads = open_pr_heads(project)

    capacity: int | None | str = "unread"  # the probe costs seconds; read it on first use
    slots = ((worker.get("runtimeConfig") or {}).get("heartbeat") or {}).get("maxConcurrentRuns") or 0
    in_flight = len(api.issues(status="todo,in_progress", assigneeAgentId=agents["Worker"]))
    # Rebases take Worker slots ahead of new work: each one is reviewed work a
    # merge away from landing, and the Coordinator promotes only into what is left.
    rebase_slots = max(0, slots - in_flight)
    handed = load_state("handoffs.json")
    handoff: list[dict] = []
    seen: dict[str, str] = {}

    def take_capacity() -> bool:
        nonlocal capacity
        if capacity == "unread":
            capacity = verify_capacity()
        if capacity is None:
            return True
        if capacity > 0:
            capacity -= 1
            return True
        return False

    def hand_off(issue: dict, sig: str, reason: str) -> None:
        seen[issue["id"]] = sig
        if handed.get(issue["id"]) != sig:
            handoff.append({"identifier": issue["identifier"], "reason": reason})

    # Held verifies first: they waited longest for a build slot.
    for held in sorted(
        (v for v in api.issues(status="todo") if stage_of(v) == "verify" and not v.get("assigneeAgentId")),
        key=lambda v: v["createdAt"],
    ):
        body = api.get(f"/issues/{held['id']}").get("description") or ""
        if HELD_VERIFY not in body or not take_capacity():
            continue
        api.set_status(
            held,
            {"status": "in_review", "assigneeAgentId": agents["Architect"]},
            "Dispatching: verify capacity is free (held at creation for lack of a build slot).",
            f"verify  {held['identifier']}: dispatch held verify",
        )

    # Oldest parent first, so a hot file's longest-waiting branch gets the slot.
    for parent, children, git_st in sorted(loaded, key=lambda t: t[0]["createdAt"]):
        if git_st is None:
            continue
        decision = decide(parent, children, git_st, pr_heads.get(f"task/{parent['identifier']}"))
        stages = ordered_stages(children)
        if decision.kind == "review":
            create_review(api, agents, parent, git_st)
        elif decision.kind == "verify":
            review = max((c for c in children if stage_of(c) == "review"), key=lambda c: c["createdAt"])
            create_verify(api, agents, parent, review, git_st, take_capacity())
        elif decision.kind == "rebase":
            if rebase_slots <= 0:
                continue
            for finished in (c for _, c in stages if finished_rebase(c)):  # a `done` one needs nothing
                api.set_status(
                    finished,
                    {"status": "done"},
                    f"Rebase finished, but `origin/main` has since moved on {decision.reason}; "
                    "a fresh rebase follows.",
                    f"rebase  {finished['identifier']}: close (main moved again)",
                )
            create_rebase(api, agents, parent, stages, git_st)
            rebase_slots -= 1
            in_flight += 1
        elif decision.kind in ("reverify", "resume-review", "close-rebase"):
            rebase = unconsumed_rebase(stages)
            follow = {
                "reverify": "The parent needs a fresh verify on the rebased head.",
                "resume-review": "The review it held resumes on the rebased head.",
                "close-rebase": "The open PR's head is this commit, so nothing further is needed here.",
            }[decision.kind]
            retire_superseded(api, agents, stages, rebase, resume=decision.kind == "resume-review")
            if rebase["status"] != "done":
                api.set_status(
                    rebase,
                    {"status": "done"},
                    f"Rebase landed: `merge-tree --write-tree origin/main HEAD` is clean at "
                    f"{git_st.head[:9]}, tree clean. {follow}",
                    f"rebase  {rebase['identifier']}: close ({decision.reason})",
                )
            if decision.kind == "reverify":
                create_verify(api, agents, parent, rebase, git_st, take_capacity())
        elif decision.kind == "handoff":
            hand_off(parent, handoff_signature(parent, children, git_st), decision.reason)

    close_landed_verifies(api, project, pr_heads)
    released = release_holds(api, pr_heads)

    # Promotion needs the Coordinator's contention rules; ask only when it could promote.
    backlog = len(api.issues(status="backlog"))
    refill_state = load_state("refill.json")
    refill = (
        slots > in_flight
        and backlog > 0
        and (released > 0 or time.time() - refill_state.get("at", 0) > REFILL_INTERVAL)
    )

    if handoff or refill:
        note = {
            "at": time.time(),
            "handoff": handoff,
            "refill": refill,
            "freeWorkerSlots": max(0, slots - in_flight),
            "backlog": backlog,
        }
        lines = [f"- {h['identifier']}: {h['reason']}" for h in handoff]
        print(("DRY " if api.dry_run else "") + f"wake    Coordinator: {len(handoff)} hand-off(s), refill={refill}")
        for line in lines:
            print("  " + line)
        if not api.dry_run:
            # Accumulate until the Coordinator takes the file (it renames it on
            # read), so two runs between its wakes cannot drop each other's entries.
            pending = {h["identifier"]: h for h in load_state(HANDOFF_FILE.name).get("handoff", [])}
            pending.update({h["identifier"]: h for h in handoff})
            note["handoff"] = list(pending.values())
            save_state(HANDOFF_FILE.name, note, False)
            api.call(
                "POST",
                f"/agents/{agents['Coordinator']}/wakeup",
                {"source": "automation", "triggerDetail": "callback", "reason": "dispatcher_handoff"},
            )
            if refill:
                save_state("refill.json", {"at": time.time()}, False)
    # Forget tasks that left the hand-off set so a later return re-notifies.
    save_state("handoffs.json", seen, api.dry_run)


def close_landed_verifies(api: Api, project: Path, pr_heads: dict[str, str]) -> None:
    """Close every `in_review` Verify whose PR is open at its landed head, or merged.

    The Coordinator's §Landing closes the Verify for a PR it opens itself; this
    covers the PRs the Architect opens, which no other step ever closed.
    """
    verifies = [v for v in api.issues(status="in_review") if stage_of(v) == "verify" and v.get("parentId")]
    if not verifies:
        return
    merged = merged_pr_numbers(project)
    for verify in verifies:
        identifier = api.get(f"/issues/{verify['parentId']}")["identifier"]
        branch = f"task/{identifier}"
        why = verify_landed(verify, pr_heads.get(branch), merged.get(branch), landed_marker(identifier))
        if why:
            api.set_status(
                verify,
                {"status": "done"},
                f"Verify complete: {why} (`{branch}`).",
                f"verify  {verify['identifier']}: close ({why})",
            )


def release_holds(api: Api, pr_heads: dict[str, str]) -> int:
    """Release `Held: until <id> ...` holds whose condition is met. Returns how many."""
    state = load_state("holds.json")
    if time.time() - state.get("at", 0) < HOLD_SCAN_INTERVAL:
        return 0
    held = [i for i in api.issues(status="blocked") if not i.get("assigneeAgentId")]

    def latest(issue: dict):
        comments = api.get(f"/issues/{issue['id']}/comments")
        newest = max(comments, key=lambda c: c["createdAt"], default=None)
        return issue, (newest or {}).get("body") or "", comments

    with concurrent.futures.ThreadPoolExecutor(8) as pool:
        triples = list(pool.map(latest, held))

    waiting = []
    legacy = 0
    for issue, body, comments in triples:
        parsed = held_until(body) or held_closed(body)
        if parsed and not overruled(comments, parsed[0]):
            waiting.append((issue, body, parsed))
        legacy += body.startswith(LEGACY_HOLD) and not parsed
    if legacy:
        # Holds naming no task stay with the Coordinator.
        print(f"holds   {legacy} in the `Held: waiting on` form with no task named; left to the Coordinator", flush=True)
    blockers: dict[str, dict | None] = {}
    released = 0
    for issue, body, (blocker_id, kind) in waiting:
        if blocker_id not in blockers:
            try:
                blockers[blocker_id] = api.get(f"/issues/{blocker_id}")
            except urllib.error.HTTPError:
                blockers[blocker_id] = None
        why = hold_resolved(blockers[blocker_id], kind, f"task/{blocker_id}" in pr_heads)
        if not why:
            continue
        quoted = body.strip().splitlines()[0]
        api.set_status(
            issue,
            {"status": "backlog"},
            f"Released: {why}.\n\n> {quoted}",
            f"release {issue['identifier']}: {why}",
        )
        released += 1
    save_state("holds.json", {"at": time.time()}, api.dry_run)
    return released


def routine_fire(issue: dict | None, agent_id: str | None) -> bool:
    """Whether the wake's task is an open routine issue assigned to this agent.

    A scheduled fire creates an issue and wakes us on it. Nothing else ever closes
    it, so without this every fire would leave one open `todo` behind.
    """
    return bool(
        issue
        and agent_id
        and issue.get("originKind") == "routine_execution"
        and issue.get("assigneeAgentId") == agent_id
        and issue.get("status") in OPEN
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    project = Path(os.environ["PAPERCLIP_PROJECT"])
    api = Api(args.dry_run)
    sweep(api, project)
    # Closed only after a sweep that returned: a crash leaves the fire's issue open as the trace.
    task_id = os.environ.get("PAPERCLIP_TASK_ID")
    issue = api.get(f"/issues/{task_id}") if task_id else None
    if routine_fire(issue, os.environ.get("PAPERCLIP_AGENT_ID")):
        api.set_status(issue, {"status": "done"}, "Sweep finished.", f"routine {issue['identifier']}: close")
    return 0


if __name__ == "__main__":
    sys.exit(main())
