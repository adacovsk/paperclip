#!/usr/bin/env python3
"""Advance finished pipeline stages without a model.

The Dispatcher is a `process` agent: the server routes every stage-completion
wake to it instead of the Coordinator (`stageDispatcherIdFor`). Those wakes were
nearly nine in ten Coordinator runs, and most of them resolved through the
mechanical rows of the Coordinator's stage table at the cost of re-reading its
whole instruction set. This script runs those rows directly:

  Worker done, committed, clean tree      -> Review subtask
  Reviewer done, needs-build              -> Verify subtask
  Reviewer done, data-only, data touched  -> Verify subtask
  rebase finished, merge-tree clean       -> close it, re-Verify the parent
                                             (or resume the Review it held)
  stage blocked on a merge conflict       -> Rebase subtask, Worker slots allowing
  held Verify, capacity free              -> dispatch it
  Verify whose landed head the PR carries -> close it (or the PR merged)
  `Held: until <id> merges|opens its PR`  -> back to backlog once it has
  `Held: waiting on <id>`, <id> closed     -> back to backlog
  its own routine fire, sweep finished      -> close the routine's issue

Everything else that is waiting on the Coordinator -- a dirty tree, no commits,
a chain, a finished rebase, an unlabeled task -- is handed off in ONE wake, and
only when its state changed since the last hand-off. The list itself is written
to HANDOFF_FILE for the Coordinator to read: a wake payload naming an issue
would make the run task-scoped and take that task's execution lock.
That wake also asks for a slot refill when Worker slots are free and backlog
holds work, because promotion needs the contention and hold rules a script
should not guess at.

Wakes coalesce per agent, so a run cannot trust its payload to name every task
that advanced. It sweeps the board instead; every action is idempotent (the
server's `(parentId, dedupeKey)` index makes a duplicate create return the
existing subtask).

    dispatch.py            sweep and act
    dispatch.py --dry-run  print the actions, write nothing
"""

from __future__ import annotations

import argparse
import concurrent.futures
import json
import os
import re
import subprocess
import sys
import time
import urllib.error
import urllib.request
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path

HERE = Path(__file__).resolve().parent
STATE_DIR = Path(os.environ.get("XDG_CACHE_HOME", Path.home() / ".cache")) / "paperclip-dispatcher"
HANDOFF_FILE = STATE_DIR / "handoff.json"
#: Hold release reads every held task's comments; once per window is plenty.
HOLD_SCAN_INTERVAL = float(os.environ.get("DISPATCHER_HOLD_SCAN_SECONDS", 300))
#: A refill wake the Coordinator just answered needs no repeat inside this window.
REFILL_INTERVAL = float(os.environ.get("DISPATCHER_REFILL_SECONDS", 300))

STAGE_KEYS = {"review": "review", "verify": "verify", "ci-fix": "verify", "rebase": "rebase"}
STAGE_PREFIXES = {"Review:": "review", "Verify:": "verify", "ci-fix:": "verify", "Rebase ": "rebase"}
OPEN = {"backlog", "todo", "in_progress", "in_review", "blocked"}
DATA_PATH = re.compile(r"^assets/(data|locales)/")
#: Paths cargo builds or tests: Rust, its manifests, and the data unit tests load.
CARGO_PATH = re.compile(r"(\.rs$|(^|/)Cargo\.(toml|lock)$|^assets/(data|locales)/)")
#: Most tasks carry their pipeline label in the body, not as an issue label.
LABEL_LINE = re.compile(r"(?im)^\W*label\W*:\W*(needs-build|data-only)\b")
#: A hold names its own release condition. `merges`: the task builds on the
#: blocker's code, which is not on main until it lands. `opens its PR`: the
#: blocker is being written on the same files (or is the previous link of a
#: same-shaped chain), and stops contending once it is finished.
HELD_UNTIL = re.compile(r"^Held: until ([A-Z]+-\d+) (merges|opens its PR)\b")
LEGACY_HOLD = "Held: waiting on "
LEGACY_HELD = re.compile(r"^Held: waiting on ([A-Z]+-\d+)\b")
#: Regenerated by the Architect's schema step, so never a reason to rebase.
SCHEMA_PATH = re.compile(r"^assets/schemas/")
#: Rebases one parent may consume. A finished rebase that conflicts again means
#: `main` moved on the same files; past this many, the file is too hot for a
#: Worker to win the race and the merge is the operator's.
MAX_REBASES = int(os.environ.get("DISPATCHER_MAX_REBASES", 3))
HELD_VERIFY = "Intended assignee: Architect (held"
VERIFY_DIR = Path(os.environ.get("XDG_CACHE_HOME", Path.home() / ".cache")) / "paperclip-verify"


# --------------------------------------------------------------------------- decisions


@dataclass(frozen=True)
class GitState:
    exists: bool
    dirty: bool = False
    ahead: int = 0
    head: str = ""
    changed: tuple[str, ...] = ()
    merges_clean: bool = False
    #: Conflicting paths against origin/main; empty when it merges clean.
    conflicts: tuple[str, ...] = ()
    #: A path origin/main deleted that the branch still modifies, with no module
    #: directory replacing it: no second version to reconcile, so the task is
    #: re-filed, not rebased.
    deleted_on_main: bool = False
    #: Deleted paths origin/main split into a module directory (`x.rs` -> `x/`).
    #: The branch's hunks have a home there, so a Worker ports them.
    split_on_main: tuple[str, ...] = ()


@dataclass(frozen=True)
class Decision:
    kind: str  # "review" | "verify" | "reverify" | "resume-review" | "close-rebase" | "rebase" | "handoff" | "skip"
    reason: str


def stage_of(child: dict) -> str | None:
    key = STAGE_KEYS.get(child.get("dedupeKey") or "")
    if key:
        return key
    for prefix, stage in STAGE_PREFIXES.items():
        if child["title"].startswith(prefix):
            return stage
    return None


def label_names(issue: dict) -> set[str]:
    return {label["name"] for label in issue.get("labels") or []}


def pipeline_label(issue: dict) -> str | None:
    """`needs-build` / `data-only` from the issue's labels, else its `Label:` line."""
    found = label_names(issue) & {"needs-build", "data-only"}
    if found:
        return "needs-build" if "needs-build" in found else "data-only"
    m = LABEL_LINE.search(issue.get("description") or "")
    return m.group(1).lower() if m else None


def finished_rebase(child: dict) -> bool:
    # A Worker never marks its own run done: a finished rebase parks at `in_review`.
    return stage_of(child) == "rebase" and child["status"] == "in_review"


def unconsumed_rebase(stages: list[tuple[str, dict]]) -> dict | None:
    """The newest rebase, if it finished and nothing has run on its head yet.

    Either still parked at `in_review`, or closed `done` by hand while the stage
    it replaced is still `blocked` -- closing it never dispatched that stage again.
    """
    if not stages or stages[-1][0] != "rebase":
        return None
    last = stages[-1][1]
    if finished_rebase(last) or (last["status"] == "done" and superseded(stages)):
        return last
    return None


def ordered_stages(children: list[dict]) -> list[tuple[str, dict]]:
    return sorted(
        ((stage_of(c), c) for c in children if stage_of(c)),
        key=lambda pair: pair[1]["createdAt"],
    )


def superseded(stages: list[tuple[str, dict]]) -> set[str]:
    """Ids of `blocked` stages a later rebase replaced.

    A Verify or Review blocks on a conflict and stays `blocked` while the rebase
    that answers it runs; once the rebase is clean, that stage describes a
    branch that no longer exists.
    """
    last = max((i for i, (stage, _) in enumerate(stages) if stage == "rebase"), default=-1)
    return {c["id"] for stage, c in stages[:last] if stage != "rebase" and c["status"] == "blocked"}


def live_stage(stages: list[tuple[str, dict]]) -> bool:
    """Whether a stage is still running.

    `blocked` is parked, not running. Counting it as live made every finished
    rebase look like it still waited on the Verify it replaced, so none was
    ever closed, and every conflict-blocked Verify hid its parent from the
    rebase dispatch: the branches sat until `main` moved past them again.
    """
    return any(c["status"] in OPEN - {"blocked"} and not finished_rebase(c) for _, c in stages)


def rebases_used(stages: list[tuple[str, dict]]) -> int:
    return sum(1 for stage, c in stages if stage == "rebase" and c["status"] != "cancelled")


def rebase_paths(git: GitState) -> tuple[str, ...]:
    return tuple(p for p in git.conflicts if not SCHEMA_PATH.match(p))


def needs_rebase(parent: dict, stages: list[tuple[str, dict]], git: GitState) -> Decision | None:
    """A rebase for a parent whose last stage stopped on a merge conflict, else None.

    Only an `in_review` parent: a `blocked` one carries someone's hold, and a
    rebase would be wasted on work that hold may cancel.
    """
    if parent["status"] != "in_review" or not stages:
        return None
    stage, last = stages[-1]
    if not ((stage in ("verify", "review") and last["status"] == "blocked") or unconsumed_rebase(stages)):
        return None
    if not git.exists or git.dirty or git.ahead == 0 or git.merges_clean:
        return None
    if git.deleted_on_main:
        return None  # modify/delete: re-filed against the new layout, not rebased
    paths = rebase_paths(git)
    if not paths:
        return None  # schemas only: regenerated, not merged
    if rebases_used(stages) >= MAX_REBASES:
        return None
    return Decision("rebase", ", ".join(paths))


def decide(parent: dict, children: list[dict], git: GitState, pr_head: str | None = None) -> Decision:
    """One parent -> what its next stage is.

    Pure, so the signal table is testable without an API or a worktree.
    """
    stages = ordered_stages(children)
    if parent["status"] in ("done", "cancelled"):
        return Decision("skip", f"parent is {parent['status']}")
    if live_stage(stages):
        return Decision("skip", "a stage is still open")
    if not git.exists:
        return Decision("handoff", "no worktree")

    if unconsumed_rebase(stages):
        # The rebase invalidated whatever verify ran before it, so the next
        # stage is a fresh one -- but only once the conflict is really gone.
        if parent["status"] != "in_review":
            return Decision("handoff", f"rebase finished on a {parent['status']} parent")
        if git.dirty or not git.merges_clean:
            again = needs_rebase(parent, stages, git)
            if again:
                return again  # `main` moved on the branch's files again since
            return Decision("handoff", "rebase finished but the branch still does not merge cleanly")
        if pr_head and pr_head == git.head:
            return Decision("close-rebase", "rebase finished and the open PR already carries it")
        dead = superseded(stages)
        if any(stage == "review" and c["id"] in dead for stage, c in stages):
            return Decision("resume-review", "rebase finished and merge-tree is clean; the review it held resumes")
        return Decision("reverify", "rebase finished and merge-tree is clean")

    rebase = needs_rebase(parent, stages, git)
    if rebase:
        return rebase
    if stages and stages[-1][1]["status"] == "blocked":
        return Decision("skip", "last stage is blocked; its block comment owns it")

    if pr_head:
        # Landed work waits on a human merge; the merge sweep owns it, whatever
        # stage ran last (a re-review after the verify is a normal history).
        return Decision("skip", "PR open")

    if not stages:
        if git.dirty:
            return Decision("handoff", "Worker finished on a dirty tree")
        if git.ahead == 0:
            return Decision("handoff", "Worker finished with no commits")
        if re.search(r"(?m)^\s*Chain:\s*\d+\s*steps", parent.get("description") or ""):
            return Decision("handoff", "chain task")
        return Decision("review", "Worker committed on a clean tree")

    stage, last = stages[-1]
    if stage == "review" and last["status"] == "done":
        # Decide by the diff as much as the label: the label was guessed at
        # intake, and most tasks carry none at all.
        label = pipeline_label(parent)
        if label == "needs-build":
            return Decision("verify", "Reviewer done, needs-build")
        if any(CARGO_PATH.search(path) for path in git.changed):
            return Decision("verify", "Reviewer done, diff touches Rust or data Rust loads")
        if label == "data-only":
            return Decision("handoff", "Reviewer done, data-only with nothing cargo reads")
        return Decision("handoff", "Reviewer done, no label and nothing cargo reads")
    if stage == "verify":
        # Landing and the merge sweep own everything after a verify.
        return Decision("skip", "verify finished; landing owns it")
    return Decision("handoff", f"last stage {stage} ended {last['status']}")


def held_until(comment: str) -> tuple[str, str] | None:
    """(blocker id, "merge" | "pr") for a hold in the release-condition form."""
    m = HELD_UNTIL.match(comment.strip())
    if not m:
        return None
    return m.group(1), "merge" if m.group(2) == "merges" else "pr"


def held_closed(comment: str) -> tuple[str, str] | None:
    """(blocker id, "closed") for a `Held: waiting on <id>` hold.

    That form does not say whether it waits on the merge or on the PR, so it is
    released only when both readings agree: the blocker is done or cancelled.
    Without this, such a hold waits on a Coordinator sweep that rarely gets that far.
    """
    m = LEGACY_HELD.match(comment.strip())
    return (m.group(1), "closed") if m else None


def hold_resolved(blocker: dict | None, kind: str, blocker_pr_open: bool) -> str | None:
    """Why a `Held: until <id> ...` hold is released, or None to keep it."""
    if blocker is None:
        return None
    if blocker["status"] in ("done", "cancelled"):
        return f"{blocker['identifier']} is {blocker['status']}"
    if kind == "pr" and blocker_pr_open:
        return f"{blocker['identifier']} has opened its PR"
    return None


def verify_landed(verify: dict, open_head: str | None, merged_pr: int | None,
                  landed: tuple[str, float] | None) -> str | None:
    """Why an `in_review` Verify has met its goal (cargo-green + PR opened), or None.

    The Architect opens its own PR, and nothing that closes a Verify runs after
    it: the server holds a no-skill task at `in_review` until its branch merges,
    and the operator merges with no Architect run on the task. `landed` is the
    Architect Landing's `{parent}.landed` marker, (head it published, mtime).
    An open PR at that head is not enough alone: a Verify re-dispatched onto a
    head that already has a PR (freshness, a stale red sentinel) starts out in
    exactly that state, with no live run while its cloud build is out. So the
    marker must postdate the Verify, and name the head the PR carries.
    """
    if verify["status"] != "in_review":
        return None
    if merged_pr is not None:
        return f"PR #{merged_pr} for its branch is merged"
    if open_head and landed and landed[0] == open_head and landed[1] > iso_ts(verify["createdAt"]):
        return f"the Architect landed {open_head[:9]} and the open PR carries it"
    return None


def iso_ts(stamp: str) -> float:
    return datetime.fromisoformat(stamp.replace("Z", "+00:00")).timestamp()


def overruled(comments: list[dict], blocker_id: str) -> bool:
    """Whether the Coordinator already re-held this task after we released it.

    The hold names its release condition, so a wrong release means the hold
    was written in the wrong form. The Coordinator's re-hold is the correction;
    releasing again would only buy another Coordinator run to re-hold it.
    """
    *earlier, _latest = sorted(comments, key=lambda c: c["createdAt"]) or [None]
    return any(
        (c.get("body") or "").startswith("Released:") and blocker_id in (c.get("body") or "")
        for c in earlier
    )


def handoff_signature(parent: dict, children: list[dict], git: GitState) -> str:
    newest = max((c["updatedAt"] for c in children), default="")
    return f"{parent['status']}|{git.head}|{git.dirty}|{newest}"


