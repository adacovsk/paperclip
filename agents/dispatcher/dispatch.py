class Api:
    def __init__(self, dry_run: bool):
        self.base = os.environ.get("PAPERCLIP_API_URL", "http://127.0.0.1:3100").rstrip("/") + "/api"
        self.company = os.environ["PAPERCLIP_COMPANY_ID"]
        self.dry_run = dry_run
        self.headers = {"Content-Type": "application/json"}
        if os.environ.get("PAPERCLIP_API_KEY"):
            self.headers["Authorization"] = f"Bearer {os.environ['PAPERCLIP_API_KEY']}"
        if os.environ.get("PAPERCLIP_RUN_ID"):
            self.headers["X-Paperclip-Run-Id"] = os.environ["PAPERCLIP_RUN_ID"]

    def call(self, method: str, path: str, body: dict | None = None):
        req = urllib.request.Request(
            self.base + path,
            data=None if body is None else json.dumps(body).encode(),
            method=method,
            headers=self.headers,
        )
        with urllib.request.urlopen(req, timeout=30) as resp:
            raw = resp.read()
            return json.loads(raw) if raw else None

    def get(self, path: str):
        return self.call("GET", path)

    def write(self, method: str, path: str, body: dict, what: str):
        print(("DRY " if self.dry_run else "") + what, flush=True)
        if self.dry_run:
            return None
        return self.call(method, path, body)

    def issues(self, **query) -> list[dict]:
        qs = "&".join(f"{k}={v}" for k, v in query.items())
        return self.get(f"/companies/{self.company}/issues?{qs}")

    def set_status(self, issue: dict, body: dict, comment: str, what: str):
        """Status and its reason in one call; on error, comment first, then PATCH."""
        try:
            self.write("PATCH", f"/issues/{issue['id']}", {**body, "comment": comment}, what)
        except urllib.error.HTTPError:
            self.write("POST", f"/issues/{issue['id']}/comments", {"body": comment}, f"  comment on {issue['identifier']}")
            self.write("PATCH", f"/issues/{issue['id']}", body, f"  retry {what}")


def git(worktree: Path, *args: str) -> str:
    return subprocess.run(
        ["git", "-C", str(worktree), *args], capture_output=True, text=True, check=True, timeout=60
    ).stdout


def git_state(project: Path, identifier: str) -> GitState:
    wt = project / ".paperclip" / "worktrees" / identifier
    if not wt.is_dir():
        return GitState(exists=False)
    try:
        dirty = bool(git(wt, "status", "--porcelain").strip())
        ahead = int(git(wt, "rev-list", "--count", "origin/main..HEAD").strip() or 0)
        head = git(wt, "rev-parse", "HEAD").strip()
        changed = tuple(git(wt, "diff", "--name-only", "origin/main...HEAD").split())
        merge = subprocess.run(
            ["git", "-C", str(wt), "merge-tree", "--write-tree", "--name-only", "origin/main", "HEAD"],
            capture_output=True, text=True, timeout=60,
        )
    except (subprocess.SubprocessError, ValueError):
        return GitState(exists=False)
    conflicts, deleted = parse_merge_tree(merge.stdout) if merge.returncode == 1 else ((), ())
    split = tuple(p for p in deleted if split_dir(p) and main_has_dir(wt, split_dir(p)))
    return GitState(
        exists=True, dirty=dirty, ahead=ahead, head=head, changed=changed,
        merges_clean=merge.returncode == 0, conflicts=conflicts,
        deleted_on_main=len(split) < len(deleted), split_on_main=split,
    )


def main_has_dir(wt: Path, path: str) -> bool:
    """Whether `origin/main` has a non-empty directory at `path`.

    A plain delete leaves no such path, and `ls-tree` exits 128 on it; that is
    the answer "not split", not an error, and raising here aborts the whole sweep.
    """
    out = subprocess.run(
        ["git", "-C", str(wt), "ls-tree", "--name-only", f"origin/main:{path}"],
        capture_output=True, text=True, timeout=60,
    )
    return out.returncode == 0 and bool(out.stdout.strip())


def split_dir(path: str) -> str | None:
    """The module directory a split of `path` would create: `a/b.rs` -> `a/b`."""
    return path[: -len(".rs")] if path.endswith(".rs") else None


def parse_merge_tree(out: str) -> tuple[tuple[str, ...], tuple[str, ...]]:
    """(conflicting paths, paths origin/main deleted) from `merge-tree --name-only`.

    The output is the tree id, one conflicted path per line, a blank line, then
    the informational messages.
    """
    head, _, messages = out.partition("\n\n")
    paths = tuple(dict.fromkeys(line for line in head.splitlines()[1:] if line))
    deleted = re.findall(r"CONFLICT \(modify/delete\): (\S+) deleted in origin/main", messages)
    return paths, tuple(dict.fromkeys(deleted))


TRAIN_HEAD = re.compile(r"^train/\d+/([A-Z]+-\d+)$")


def by_head(prs: list[dict], field: str) -> dict[str, object]:
    """{head branch: pr[field]}, with each `train/<n>/<id>` head also keyed as `task/<id>`.

    A train PR carries a task's work cherry-picked onto a stack, so it is that
    task's PR: every lookup here is keyed `task/<id>`, and without the alias a
    train-PR'd task reads as having no PR at all — its holds never release and
    it gets dispatched for work that is already in review. A real `task/<id>`
    head wins over the alias.
    """
    out: dict[str, object] = {pr["headRefName"]: pr[field] for pr in prs}
    for pr in prs:
        m = TRAIN_HEAD.match(pr["headRefName"])
        if m:
            out.setdefault(f"task/{m.group(1)}", pr[field])
    return out


def open_pr_heads(project: Path) -> dict[str, str]:
    """Open PRs as {head branch: head commit}."""
    out = subprocess.run(
        ["gh", "pr", "list", "--state", "open", "--limit", "500", "--json", "headRefName,headRefOid"],
        cwd=project, capture_output=True, text=True, timeout=60, check=True,
    ).stdout
    return by_head(json.loads(out), "headRefOid")


def merged_pr_numbers(project: Path) -> dict[str, int]:
    """Recently merged PRs as {head branch: number}."""
    out = subprocess.run(
        ["gh", "pr", "list", "--state", "merged", "--limit", "300", "--json", "headRefName,number"],
        cwd=project, capture_output=True, text=True, timeout=60, check=True,
    ).stdout
    return by_head(json.loads(out), "number")


def landed_marker(identifier: str) -> tuple[str, float] | None:
    path = VERIFY_DIR / f"{identifier}.landed"
    try:
        return path.read_text().strip(), path.stat().st_mtime
    except OSError:
        return None


def verify_capacity() -> int | None:
    """Verifies that may still be dispatched now; None means unbounded (cloud lane open)."""
    lane = subprocess.run(
        [sys.executable, str(HERE.parent / "architect" / "cloud-pace.py")],
        capture_output=True, text=True, timeout=60,
    ).stdout.strip()
    if lane == "1":
        return None
    try:
        slots = int(Path("/tmp/cargo-sem.slots").read_text().strip())
    except (OSError, ValueError):
        slots = 2
    live = subprocess.run(
        [str(HERE.parent / "architect" / "verify-census.sh")], capture_output=True, text=True, timeout=60,
    ).stdout.split()
    return max(0, 2 * slots - len(live))


def load_state(name: str) -> dict:
    try:
        return json.loads((STATE_DIR / name).read_text())
    except (OSError, ValueError):
        return {}


def save_state(name: str, data: dict, dry_run: bool) -> None:
    if dry_run:
        return
    STATE_DIR.mkdir(parents=True, exist_ok=True)
    (STATE_DIR / name).write_text(json.dumps(data))


# --------------------------------------------------------------------------- actions


def worktree_lines(identifier: str) -> tuple[str, str]:
    return f".paperclip/worktrees/{identifier}", f"task/{identifier}"


def issue_link(identifier: str) -> str:
    return f"[{identifier}](/{identifier.split('-')[0]}/issues/{identifier})"


def create_review(api: Api, agents: dict, parent: dict, git_st: GitState):
    wt, branch = worktree_lines(parent["identifier"])
    label = pipeline_label(parent) or "none"
    files = "\n".join(f"- {p}" for p in git_st.changed) or "- (none)"
    body = (
        f"What: review {branch} against the parent's What/Done-when.\n"
        f"Why: Worker stage complete, commit {git_st.head[:9]}.\n"
        f"Where: worktree {wt} (branch {branch}).\n"
        f"Changed files:\n{files}\n"
        f"Done-when: diff satisfies parent Done-when; Reviewer commits any fixes.\n"
        f"Label: {label}\n\n"
        f"worktree: {wt} (branch {branch})\n"
    )
    api.write(
        "POST",
        f"/companies/{api.company}/issues",
        {
            "title": f"Review: {parent['identifier']} {parent['title']}"[:200],
            "description": body,
            "status": "in_review",
            "priority": parent.get("priority") or "medium",
            "parentId": parent["id"],
            "goalId": parent.get("goalId"),
            "assigneeAgentId": agents["Reviewer"],
            "dedupeKey": "review",
        },
        f"review  {parent['identifier']}: create Review subtask",
    )


def create_verify(api: Api, agents: dict, parent: dict, after: dict, git_st: GitState, dispatch: bool):
    wt, branch = worktree_lines(parent["identifier"])
    held = "" if dispatch else "\nIntended assignee: Architect (held — no verify capacity free)\n"
    where = ", ".join(f"`{p}`" for p in git_st.changed) or "(see branch)"
    body = (
        f"worktree: {wt}\nbranch:   {branch}\n\n"
        "**What** — Run `cargo clippy --all-targets` and `cargo test` against the worktree above, "
        "fix what they report, commit, and open the PR.\n\n"
        f"**Why** — {issue_link(parent['identifier'])}: {parent['title']}. "
        f"{after['title'].split(':')[0].split()[0]} {issue_link(after['identifier'])} is done.\n\n"
        f"**Where** — {where}\n{held}"
    )
    label_ids = [l["id"] for l in parent.get("labels") or [] if l["name"] == "needs-build"]
    api.write(
        "POST",
        f"/companies/{api.company}/issues",
        {
            "title": f"Verify: {parent['identifier']} {parent['title']}"[:200],
            "description": body,
            "status": "in_review" if dispatch else "todo",
            "priority": parent.get("priority") or "medium",
            "parentId": parent["id"],
            "goalId": parent.get("goalId"),
            "assigneeAgentId": agents["Architect"] if dispatch else None,
            "dedupeKey": "verify",
            **({"labelIds": label_ids} if label_ids else {}),
        },
        f"verify  {parent['identifier']}: create Verify subtask ({'dispatched' if dispatch else 'held'})",
    )


def create_rebase(api: Api, agents: dict, parent: dict, stages: list[tuple[str, dict]], git_st: GitState):
    wt, branch = worktree_lines(parent["identifier"])
    paths = rebase_paths(git_st)
    n = rebases_used(stages) + 1
    body = (
        f"Rebase `{branch}` onto `origin/main` and resolve the conflict in "
        + ", ".join(f"`{p}`" for p in paths)
        + ". The implementation on this branch is already complete and reviewed — do not "
        "re-implement it. Leave any `assets/schemas/` conflict on main's side; the Architect "
        "regenerates schemas. "
        + "".join(
            f"`origin/main` split `{p}` into `{split_dir(p)}/`: move this branch's changes to it "
            f"(`git diff origin/main...HEAD -- {p}`) into the matching modules there, then "
            f"`git rm {p}`. "
            for p in git_st.split_on_main
        )
        + "Done-when: `git merge-tree --write-tree origin/main HEAD` exits 0 and the tree is clean.\n\n"
        f"worktree: {project_root()}/{wt} (branch {branch})\n\n"
        f"Rebase task for {parent['identifier']}; Worker rebase: {n}.\n"
    )
    api.write(
        "POST",
        f"/companies/{api.company}/issues",
        {
            "title": f"Rebase {branch} onto origin/main",
            "description": body,
            "status": "todo",
            "priority": parent.get("priority") or "medium",
            "parentId": parent["id"],
            "goalId": parent.get("goalId"),
            "assigneeAgentId": agents["Worker"],
            "dedupeKey": "rebase",
        },
        f"rebase  {parent['identifier']}: create Rebase subtask #{n} ({', '.join(paths)})",
    )


def project_root() -> str:
    return os.environ["PAPERCLIP_PROJECT"].rstrip("/")


def latest_body(api: Api, issue: dict) -> str:
    comments = api.get(f"/issues/{issue['id']}/comments")
    newest = max(comments, key=lambda c: c["createdAt"], default=None)
    return ((newest or {}).get("body") or "").strip()


def retire_superseded(api: Api, agents: dict, stages: list[tuple[str, dict]], rebase: dict, resume: bool):
    """Retire the blocked stages a clean rebase answered.

    A superseded Verify is cancelled: the server dedupes open subtasks on
    `(parentId, dedupeKey)`, so a fresh Verify cannot be created beside it, and
    its block comment describes a branch that no longer exists. A superseded
    Review is resumed instead when `resume` is set -- it never ran.
    """
    dead = superseded(stages)
    for stage, child in stages:
        if child["id"] not in dead:
            continue
        quoted = (latest_body(api, child).splitlines() or ["(no block comment)"])[0]
        if stage == "review" and resume:
            api.set_status(
                child,
                {"status": "in_review", "assigneeAgentId": agents["Reviewer"]},
                f"Released: {rebase['identifier']} rebased the branch and `merge-tree` is clean.\n\n> {quoted}",
                f"review  {child['identifier']}: resume after {rebase['identifier']}",
            )
        else:
            api.set_status(
                child,
                {"status": "cancelled"},
                f"Superseded: {rebase['identifier']} rebased the branch and `merge-tree` is clean; "
                f"a fresh stage runs on the rebased head.\n\n> {quoted}",
                f"{stage:<7} {child['identifier']}: cancel, superseded by {rebase['identifier']}",
            )


